package org.contikios.cooja.interfaces;

import java.util.Map;
import org.contikios.cooja.MoteInterface;

/**
 * Exposes diagnostic state published by a mote, for simulation-side logging.
 *
 * <p>The map is implementation-defined and must contain only JSON-serializable
 * values: numbers, booleans, strings, maps, and lists. The simulator does not
 * interpret the keys; a plugin may sample and serialize them without knowing
 * which application or protocol produced them.
 */
public interface DiagState extends MoteInterface {

  /**
   * Returns the latest coherent state, or {@code null} when no sample is
   * available.
   */
  Map<String, Object> getState();
}
